@app.get("/site/read")
async def site_read(site_name: str = Query(...), path: str = Query(...)):
    target = safe_site_file(site_name, path)
    if not target.exists() or not target.is_file():
        raise HTTPException(status_code=404, detail="File not found")
    data = target.read_bytes()
    if len(data) > 1_000_000:
        raise HTTPException(status_code=400, detail="File too large")
    return {"status": "ok", "site_name": normalize_site_name(site_name), "path": path, "content": data.decode("utf-8", errors="ignore")}

@app.post("/site/write")
async def site_write(req: SiteWriteRequest):
    target = safe_site_file(req.site_name, req.path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(req.content or "", encoding="utf-8")
    return {"status": "ok", "site_name": normalize_site_name(req.site_name), "path": req.path, "bytes": len((req.content or "").encode("utf-8"))}




async def sites():
    ROOT.mkdir(parents=True, exist_ok=True)
    rows = []
    for p in sorted(ROOT.glob("*")):
        if p.is_dir():
            rows.append({"site_name": p.name, "path": str(p), "updated_at": int(p.stat().st_mtime)})
    db_rows = []
    try:
        conn = db_conn(); cur = conn.cursor(dictionary=True)
        cur.execute("SELECT id, created_at, site_name, title, root_path, status, details_json FROM site_projects ORDER BY id DESC LIMIT 200")
        db_rows = cur.fetchall()
        cur.close(); conn.close()
    except Exception:
        pass
    return {"status": "ok", "filesystem_sites": rows, "db_sites": db_rows}

@app.post("/scaffold")
async def scaffold(req: ScaffoldRequest):
    site_name = normalize_site_name(req.site_name)
    root = safe_site_path(site_name)
    root.mkdir(parents=True, exist_ok=True)
    (root / "index.html").write_text(
        f"<!DOCTYPE html><html><head><meta charset='UTF-8'><meta name='viewport' content='width=device-width,initial-scale=1'><title>{req.title}</title><link rel='stylesheet' href='styles.css'></head><body><main><h1>{req.title}</h1><p>Scaffold generated by Luminax Site Manager.</p><button id='statusBtn'>Check Status</button><pre id='out'></pre></main><script src='app.js'></script></body></html>",
        encoding="utf-8",
    )
    (root / "styles.css").write_text(
        "body{font-family:Segoe UI,Arial,sans-serif;background:#0b1220;color:#d7e6ff;margin:0;padding:2rem}main{max-width:980px;margin:auto}button{padding:.7rem 1rem;border:0;border-radius:.6rem;background:#4ce0c6;color:#04131a;font-weight:700;cursor:pointer}",
        encoding="utf-8",
    )
    (root / "app.js").write_text(
        "document.getElementById('statusBtn').addEventListener('click',()=>{document.getElementById('out').textContent='Luminax site scaffold is operational.';});",
        encoding="utf-8",
    )
    try:
        conn = db_conn(); cur = conn.cursor(dictionary=True)
        cur.execute("SELECT id FROM site_projects WHERE site_name=%s ORDER BY id DESC LIMIT 1", (site_name,))
        row = cur.fetchone()
        cur.close()
        cur2 = conn.cursor()
        if row:
            cur2.execute(
                "UPDATE site_projects SET title=%s, root_path=%s, status=%s, details_json=%s WHERE id=%s",
                (req.title, str(root), "scaffolded", json.dumps({"updated_at": int(time.time())}), int(row["id"])),
            )
        else:
            cur2.execute(
                "INSERT INTO site_projects (site_name, title, root_path, status, details_json) VALUES (%s,%s,%s,%s,%s)",
                (site_name, req.title, str(root), "scaffolded", json.dumps({"updated_at": int(time.time())})),
            )
        conn.commit(); cur2.close(); conn.close()
    except Exception:
        pass
    return {"status": "ok", "site_name": site_name, "site_root": str(root)}

@app.post("/publish")
async def publish(req: PublishRequest):
    site_name = normalize_site_name(req.site_name)
    site_root = safe_site_path(site_name)
    if not site_root.exists():
        raise HTTPException(status_code=404, detail="Site not found")
    PUBLISHED_ROOT.mkdir(parents=True, exist_ok=True)
    target = (PUBLISHED_ROOT / site_name).resolve()
    if not str(target).startswith(str(PUBLISHED_ROOT.resolve())):
        raise HTTPException(status_code=400, detail="Invalid publish target")
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(site_root, target)
    details = {"published_at": int(time.time()), "publish_mode": req.mode, "published_path": str(target)}
    try:
        conn = db_conn(); cur = conn.cursor()
        cur.execute(
            "UPDATE site_projects SET status=%s, details_json=%s WHERE site_name=%s",
            ("published", json.dumps(details), site_name),
        )
        conn.commit(); cur.close(); conn.close()
    except Exception:
        pass
    return {"status": "published", "site_name": site_name, "site_root": str(site_root), "published_root": str(target)}


from runtime_guard import (runtime_enabled, feature_enabled, token_matches, require_feature, install_runtime_guard)
import json, os, shutil, time
from pathlib import Path
import mysql.connector
from fastapi import FastAPI, HTTPException, Query
from pydantic import BaseModel

app = FastAPI(title="Luminax Site Manager")
MYSQL_HOST = os.getenv("MYSQL_HOST", "mysql")
MYSQL_PORT = int(os.getenv("MYSQL_PORT", "3306"))
MYSQL_DATABASE = os.getenv("MYSQL_DATABASE", "luminax")
MYSQL_USER = os.getenv("MYSQL_USER", "")
MYSQL_PASSWORD = os.getenv("MYSQL_PASSWORD", "")
ROOT = Path("/workspace/luminax/sites")
PUBLISHED_ROOT = Path("/workspace/luminax/published_sites")

class PublishRequest(BaseModel):
    site_name: str
    mode: str = "copy"

class ScaffoldRequest(BaseModel):
    site_name: str
    title: str

class SiteWriteRequest(BaseModel):
    site_name: str
    path: str
    content: str

def db_conn():
    return mysql.connector.connect(host=MYSQL_HOST, port=MYSQL_PORT, user=MYSQL_USER, password=MYSQL_PASSWORD, database=MYSQL_DATABASE)

def normalize_site_name(raw: str) -> str:
    safe = "".join(ch for ch in (raw or "").strip().lower() if ch.isalnum() or ch in "-_").strip("-_")
    if not safe:
        raise HTTPException(status_code=400, detail="Invalid site name")
    return safe[:120]

def safe_site_path(site_name: str) -> Path:
    safe = normalize_site_name(site_name)
    path = (ROOT / safe).resolve()
    if not str(path).startswith(str(ROOT.resolve())):
        raise HTTPException(status_code=400, detail="Invalid site root")
    return path

def safe_site_file(site_name: str, rel_path: str) -> Path:
    base = safe_site_path(site_name)
    rel = (rel_path or "").strip().lstrip("/").replace("\\", "/")
    target = (base / rel).resolve()
    if not str(target).startswith(str(base)):
        raise HTTPException(status_code=400, detail="Path outside site root")
    return target

@app.get("/health")
async def health():
    ROOT.mkdir(parents=True, exist_ok=True)
    PUBLISHED_ROOT.mkdir(parents=True, exist_ok=True)
    return {"status": "ok", "sites_root": str(ROOT), "published_root": str(PUBLISHED_ROOT)}

